/**
 * Logits from llama.cpp, for the forward pass (#184).
 *
 * **Not produced by this code.**  Generated by `tools/reflogits`, which loads
 * the *same GGUF file* with llama.cpp and dumps the logits for the final
 * position of one forward pass.  Reading the same file matters: #180 found
 * that `modeling_gemma2.py` describes the HuggingFace checkpoint and the GGUF
 * is a different artefact, so an oracle built from HF weights would carry the
 * error it is meant to catch.
 *
 * llama.cpp commit: 7049ff0cb
 * Dumped on CPU (`-ngl 0`), because a reference wants to be reproducible
 * before it wants to be fast.
 *
 * Recorded rather than computed at test time, which is the same choice
 * `llama3_tokens.hh` makes and for a stronger reason here: llama.cpp changes
 * its own kernels, so a live binary would make this test's meaning drift with
 * somebody else's release schedule.  The commit is above so the fixture can
 * be regenerated and disagreements attributed.
 *
 * **The ids are the input, not the text.**  jlib's tokenizer is verified
 * against the same vendor files separately, so feeding ids keeps tokenization
 * out of a comparison that is about arithmetic.  The prompt text is recorded
 * only so a reader knows what was asked.
 */
struct reference_logits {
    const char*  model;        ///< the GGUF this was dumped from
    const char*  prompt;       ///< what the ids spell, for the reader
    int          ids[16];      ///< the forward pass input
    int          id_count;
    int          vocab;        ///< so a mismatched file is caught, not compared
    int          top_id[64];    ///< the reference's most likely tokens, in order
    float        top_logit[64]; ///< and their logits
    int          stride;       ///< sample[j] is the logit of token j*stride
    float        sample[256];
};


